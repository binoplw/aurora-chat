	private static void add(String icon, String name, boolean wide, String... items) {
		// «Сезон · стикеры» дописываются к уже добавленному сезону
		if (wide && !CATS.isEmpty() && name.startsWith(CATS.get(CATS.size() - 1).name() + " ·")) {
			Cat last = CATS.remove(CATS.size() - 1);
			CATS.add(new Cat(last.icon(), last.name(), last.items(), List.of(items)));
		} else if (wide) CATS.add(new Cat(icon, name, List.of(), List.of(items)));
		else CATS.add(new Cat(icon, name, List.of(items), List.of()));
	}

