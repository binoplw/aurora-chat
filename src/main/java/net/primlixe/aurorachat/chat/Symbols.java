	/** Набор по текущему времени года: декабрь–февраль зима, март–май весна, июнь–август лето, иначе осень. */
	public static int seasonIndex() {
		int m = LocalDate.now().getMonthValue();
		String name = m == 12 || m <= 2 ? "Зима" : m <= 5 ? "Весна" : m <= 8 ? "Лето" : "Осень";
		for (int i = 0; i < CATS.size(); i++) if (CATS.get(i).name().equals(name)) return i;
		return 0;
	}

